def load_target_image(file_path):
    if not os.path.exists(file_path):
        return None
    try:
        pil_img = Image.open(file_path).convert('RGB')
        return cv2.cvtColor(np.array(pil_img), cv2.COLOR_RGB2BGR)
    except Exception as e:
        print(f"Error loading {file_path}: {e}")
        return None

def process_hd_face_swap_stable(user_photo, style_choice, enable_hd=True):
    """
    Robust Face Swap + HD Enhancement using Native OpenCV.
    Guaranteed zero dependency crashes.
    """
    if user_photo is None:
        return None, None, "Please upload a photo!"

    # Map selection to target image
    if style_choice == "Traditional Saudi Attire":
        target_img = load_target_image("saudi_custom.avif")
        if target_img is None:
            target_img = load_target_image("saudi_traditional.jpg")
    else:
        target_img = load_target_image("vision_2030_astronaut.jpg")

    if target_img is None:
        return None, None, "Error: Template image missing in Colab workspace."

    # Convert uploaded image to OpenCV format
    source_img = cv2.cvtColor(np.array(user_photo), cv2.COLOR_RGB2BGR)

    # Detect faces
    source_faces = app.get(source_img)
    target_faces = app.get(target_img)

    if len(source_faces) == 0 or len(target_faces) == 0:
        return cv2.cvtColor(target_img, cv2.COLOR_BGR2RGB), None, "Face detection failed! Ensure face is clearly visible."

    # 1. Perform Face Swap
    swapped_img = swapper.get(target_img, target_faces[0], source_faces[0], paste_back=True)

    # 2. Apply HD Detail Enhancement (Sharpening + Contrast)
    if enable_hd:
        # Sharpens facial features (eyes, beard, nose) without breaking pixel matrices
        enhanced_img = cv2.detailEnhance(swapped_img, sigma_s=10, sigma_r=0.15)
        # Smooth color blending slightly for clean skin tone
        final_img = cv2.bilateralFilter(enhanced_img, d=5, sigmaColor=50, sigmaSpace=50)
    else:
        final_img = swapped_img

    # Convert OpenCV BGR format back to RGB for browser rendering
    result_rgb = cv2.cvtColor(final_img, cv2.COLOR_BGR2RGB)

    return result_rgb, "shutter.mp3", "✨ HD Transformation Complete!"

