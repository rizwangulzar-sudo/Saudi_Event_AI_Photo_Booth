def find_image(base_name):
    possible_extensions = ['.jpg', '.jpeg', '.png', '.JPG', '.JPEG', '.PNG']
    for ext in possible_extensions:
        full_path = base_name + ext
        if os.path.exists(full_path):
            return full_path
        if os.path.exists(base_name): # Direct filename check
            return base_name
    return None

